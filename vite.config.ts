import { createHash } from 'node:crypto';
import { defineConfig, type Plugin } from 'vite';
import basicSsl from '@vitejs/plugin-basic-ssl';

const PUBLIC_FILES = [
  'manifest.webmanifest',
  'icons/icon.svg',
  'icons/icon-192.png',
  'icons/icon-512.png',
  'icons/icon-maskable-512.png',
  'icons/apple-touch-icon.png',
];

/**
 * Emits sw.js with the build's file list baked in, so the app opens offline
 * after one visit (including lazily loaded chunks such as the compression
 * model). Cache name changes whenever the file list does.
 */
function serviceWorker(): Plugin {
  return {
    name: 'earshot-sw',
    apply: 'build',
    generateBundle(_, bundle) {
      const files = ['./', ...Object.keys(bundle).filter((f) => f !== 'index.html'), ...PUBLIC_FILES];
      const version = createHash('sha256').update(files.join('\n')).digest('hex').slice(0, 12);
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: swSource(`earshot-${version}`, files) });
    },
  };
}

function swSource(cacheName: string, files: string[]): string {
  return `// generated by vite.config.ts
const CACHE = ${JSON.stringify(cacheName)};
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  if (req.mode === 'navigate') {
    // network first so a new deploy shows up; cached shell when offline
    e.respondWith(fetch(req).catch(() => caches.match('./')));
    return;
  }
  // hashed assets never change: cache first
  e.respondWith(caches.match(req).then((hit) => hit || fetch(req)));
});
`;
}

export default defineConfig({
  // relative base works for both username.github.io/earshot/ and local preview
  base: './',
  plugins: [basicSsl(), serviceWorker()],
  server: { host: true },
});
